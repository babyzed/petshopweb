#!/usr/bin/env bash
# ============================================================
# استقرار و به‌روزرسانی پت‌شاپ با داکر
#
# اجرا روی سرور:
#   ./deploy.sh
#
# این اسکریپت:
#   1) از دیتابیس فعلی پشتیبان می‌گیرد (پوشه backups/)
#   2) آخرین نسخه کد را از گیت می‌گیرد (git pull)
#   3) تصویر داکر را دوباره می‌سازد و سایت را بالا می‌آورد
# داده‌ها (دیتابیس + آپلودها) در Volume می‌مانند و از بین نمی‌روند.
# ============================================================
set -euo pipefail
cd "$(dirname "$0")"

echo "📦 پت‌شاپ — استقرار/به‌روزرسانی"
echo "--------------------------------"

# 1) پشتیبان‌گیری
mkdir -p backups
if [ -f data/petshop.db ]; then
  BK="backups/petshop-$(date +%Y%m%d-%H%M%S).db"
  cp data/petshop.db "$BK"
  echo "✅ پشتیبان دیتابیس: $BK"
fi

# 2) دریافت آخرین نسخه (اگر مخزن گیت با remote تنظیم شده باشد)
if [ -d .git ]; then
  echo "⬇️  دریافت آخرین نسخه از گیت..."
  git pull --rebase || echo "⚠️  git pull ناموفق بود؛ با نسخه فعلی ادامه می‌دهیم."
else
  echo "ℹ️  مخزن گیت نیست — از فایل‌های فعلی استفاده می‌شود."
fi

# 3) ساخت و اجرا
echo "🐳 ساخت تصویر داکر و بالا آوردن سایت..."
docker compose up -d --build

echo "--------------------------------"
echo "✅ سایت بالا آمد!"
echo "   فروشگاه: http://localhost:3000"
echo "   پنل مدیریت: http://localhost:3000/admin"
echo "   وضعیت: docker compose ps"
echo "   لاگ‌ها: docker compose logs -f --tail=100"
